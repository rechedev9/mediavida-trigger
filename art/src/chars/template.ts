function walk(prefix: "down" | "up", head: string): PoseFrame[] {
  const view = prefix;
  return [
    { body: `${prefix}-step-l`, head, view, dy: 1, ms: WALK },
    { body: `${prefix}-idle`, head, view, dy: 0, ms: WALK },
    { body: `${prefix}-step-r`, head, view, dy: 1, ms: WALK },
    { body: `${prefix}-idle`, head, view, dy: 0, ms: WALK },
  ];
}

