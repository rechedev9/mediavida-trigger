import type { Element, FxId, TechDef, TechKind, TechTarget } from "./types";
import type { SfxId } from "../audio/audio";

type TechSpec = {
  name: string;
  desc: string;
  mp: number;
  kind: TechKind;
  element?: Element;
  power: number;
  target: TechTarget;
  users: string[];
  minLevel?: number;
  fx: FxId;
  sfx?: SfxId;
};

const SFX_BY_ELEMENT: Record<Element, SfxId> = {
  fuego: "fire",
  hielo: "ice",
  rayo: "bolt",
  sombra: "shadow",
};

function defaultSfx(spec: TechSpec): SfxId {
  if (spec.element) return SFX_BY_ELEMENT[spec.element];
  if (spec.kind === "heal" || spec.kind === "revive" || spec.kind === "buff") return "heal";
  return "hit";
}

