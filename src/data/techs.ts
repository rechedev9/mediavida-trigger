const TECHS: Record<string, TechDef> = Object.fromEntries(
  Object.entries(SPECS).map(([id, s]) => [
    id,
    {
      id,
      name: s.name,
      desc: s.desc,
      mp: s.mp,
      kind: s.kind,
      element: s.element ?? null,
      power: s.power,
      target: s.target,
      users: s.users,
      minLevel: s.minLevel ?? 1,
      fx: s.fx,
      sfx: s.sfx ?? defaultSfx(s),
    },
  ]),
);

export function techDef(id: string): TechDef | null {
  return TECHS[id] ?? null;
}

export function comboTechs(): TechDef[] {
  return Object.values(TECHS).filter((t) => t.users.length > 1);
}
