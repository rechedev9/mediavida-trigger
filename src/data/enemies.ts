import type { EnemyAttack, EnemyDef, Stats } from "./types";

function stats(level: number, bias: Partial<Stats> = {}): Stats {
  const v = 4 + level * 1.4;
  return {
    fuerza: Math.round(v * (bias.fuerza ?? 1)),
    aguante: Math.round(v * (bias.aguante ?? 1)),
    velocidad: Math.round((8 + level * 0.5) * (bias.velocidad ?? 1)),
    magia: Math.round(v * (bias.magia ?? 1)),
    precision: Math.round((8 + level * 0.6) * (bias.precision ?? 1)),
    evasion: Math.round((5 + level * 0.5) * (bias.evasion ?? 1)),
    defMagica: Math.round(v * (bias.defMagica ?? 1)),
  };
}

