export const ENEMIES: Record<string, EnemyDef> = Object.fromEntries(
  Object.entries(SPECS).map(([id, s]) => [
    id,
    {
      id,
      name: s.name,
      level: s.level,
      hp: s.hp,
      stats: stats(s.level, s.bias),
      xp: s.xp,
      karma: s.karma,
      weak: s.weak ?? [],
      resist: s.resist ?? [],
      absorb: s.absorb ?? [],
      attacks: s.attacks,
      drop: s.drop ?? null,
      boss: s.boss ?? false,
      color: s.color,
      size: s.size ?? [32, 32],
    },
  ]),
);

export function enemyDef(id: string): EnemyDef {
  const def = ENEMIES[id];
  if (!def) throw new Error(`Enemigo desconocido: ${id}`);
  return def;
}
